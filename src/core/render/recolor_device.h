// Замена цветов документа (план 2.5b; эталон 3.16 «Замена цветов / ночной режим»; view-26, ocr-38, ocr-45):
// своё устройство fz_device поверх draw device — заливки и обводки текста и векторов (fill/stroke_text,
// fill/stroke_path, маски-картинки fill_image_mask) получают цвет по яркости исходного между парой «текст /
// фон»: чёрное → цвет текста, белое → цвет фона, серое — между ними (так тёмная плашка с белым текстом
// остаётся читаемой). Картинки и градиенты не трогаются («только текст и линии», как в Acrobat); содержимое
// мягких масок (begin_mask…end_mask) — тоже: иначе маска исказится. Бумагу закрашивает цветом фона
// renderDisplayList. «Изменять только чёрный текст и графику» (onlyBlack) — чёрное → текст, белое → фон,
// цветное как было; lineArt = false — векторы как были (только текст). «Инвертировать всё» (InvertAll) — не
// устройство, а инверсия готового растра (renderDisplayList), картинки тоже. Пара цветов — из настроек и
// токенов ui (ночь, высокая контрастность, свои); ядро получает их числами.
#pragma once

#include "core/render/render_style.h"

extern "C" {
#include <mupdf/fitz.h>
}

namespace ot {

// Устройство-обёртка: всё передаёт target (draw device), подменяя цвета по rc. target не принадлежит
// устройству и закрывается вместе с ним (close_device). Ошибки MuPDF — fz_throw (зовущий — внутри mu::call).
fz_device* newRecolorDevice(fz_context* ctx, fz_device* target, const Recolor& rc);

}  // namespace ot
